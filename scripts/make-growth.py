def guide_json(name, g):
    return {
        "species": name, "hotSpot": g["hotSpot"], "preyPercent": g["preyPercent"],
        "hatchling": g["hatchling"],
        "breedingFemale": {"grams": g["breedingFemale"][0], "months": g["breedingFemale"][1]},
        "breedingMale": {"grams": g["breedingMale"][0], "months": g["breedingMale"][1]},
        "stages": [{"upTo": s[0], "label": s[1], "minDays": s[2], "maxDays": s[3]} for s in g["stages"]],
        "curve": [{"months": c[0], "low": c[1], "high": c[2]} for c in g["curve"]],
        "tips": g["tips"],
    }

root = pathlib.Path(__file__).resolve().parent.parent
guides = [guide_json(n, g) for n, g in GUIDES.items()]
(root / "web/js/growth-data.js").write_text(
    "// Generated by scripts/make-growth.py. Do not edit.\n"
    f"export const GENERAL_TIPS = {json.dumps(GENERAL_TIPS, indent=1, ensure_ascii=False)};\n\n"
    f"export const GROWTH_GUIDES = {json.dumps(guides, indent=1, ensure_ascii=False)};\n")

def s(x): return json.dumps(x, ensure_ascii=False)
lines = ["// Generated by scripts/make-growth.py. Do not edit.", "", "extension GrowthGuide {",
         "    public static let generalTips: [String] = [", *[f"        {s(t)}," for t in GENERAL_TIPS], "    ]", "",
         "    public static let all: [GrowthGuide] = ["]
for g in guides:
    stages = ", ".join(f"Stage(upTo: {st['upTo'] if st['upTo'] is not None else 'nil'}, label: {s(st['label'])}, minDays: {st['minDays']}, maxDays: {st['maxDays']})" for st in g["stages"])
    curve = ", ".join(f"CurvePoint(months: {c['months']}, low: {c['low']}, high: {c['high']})" for c in g["curve"])
    lines += [
        "        GrowthGuide(",
        f"            species: {s(g['species'])}, hotSpot: {s(g['hotSpot'])},",
        f"            preyPercent: {g['preyPercent'][0]}...{g['preyPercent'][1]},",
        f"            hatchling: {g['hatchling'][0]}...{g['hatchling'][1]},",
        f"            breedingFemale: Target(grams: {g['breedingFemale']['grams']}, months: {g['breedingFemale']['months']}),",
        f"            breedingMale: Target(grams: {g['breedingMale']['grams']}, months: {g['breedingMale']['months']}),",
        f"            stages: [{stages}],",
        f"            curve: [{curve}],",
        f"            tips: [{', '.join(s(t) for t in g['tips'])}]",
        "        ),",
    ]
lines += ["    ]", "}", ""]
(root / "SnakeGenetics/Sources/SnakeGenetics/GrowthData.swift").write_text("\n".join(lines))
print(f"{len(guides)} species guides")
