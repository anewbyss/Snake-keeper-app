#!/usr/bin/env python3
"""Generates web/js/genes.js from SnakeGenetics/Sources/SnakeGenetics/GeneLibrary.swift,
so the web app and the native app share one gene library. Re-run after editing the Swift file."""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "SnakeGenetics/Sources/SnakeGenetics/GeneLibrary.swift").read_text()

def arg(call, name):
    m = re.search(name + r':\s*"([^"]*)"', call)
    return m.group(1) if m else None

species = []
for m in re.finditer(r'static let \w+ = Species\(\s*name: "([^"]+)",\s*scientificName: "([^"]+)",\s*incubationDays: (\w+),\s*genes: \[(.*?)\n        \]', src, re.S):
    name, sci, inc, body = m.groups()
    genes = []
    for call in re.finditer(r'\b(rec|inc|dom)\("(\w+)", "([^"]+)"(.*?)\)(?:,|\n)', body):
        kind, prefix, gname, rest = call.groups()
        gid = arg(rest, "id") or re.sub(r'[^a-z0-9]', '', gname.lower())
        locus = arg(rest, "locus")
        gene = {
            "id": f"{prefix}.{gid}",
            "name": gname,
            "inheritance": {"rec": "recessive", "inc": "incompleteDominant", "dom": "dominant"}[kind],
            "locus": f"{prefix}.{locus}" if locus else f"{prefix}.{gid}",
        }
        for key in ("superName", "warning", "homozygousWarning"):
            if arg(rest, key): gene[key] = arg(rest, key)
        genes.append(gene)
    species.append({"name": name, "scientificName": sci,
                    "incubationDays": None if inc == "nil" else int(inc), "genes": genes})

compounds = {}
bel = re.search(r'let bel = \[(.*?)\]', src).group(1)
bel = re.findall(r'"([^"]+)"', bel)
for a in bel:
    for b in bel:
        if a < b: compounds["|".join(sorted([a, b]))] = "Blue Eyed Leucistic"
for a, b, n in re.findall(r'compoundKey\("([^"]+)", "([^"]+)"\)\] = "([^"]+)"', src):
    compounds["|".join(sorted([a, b]))] = n

out = ("// Generated by scripts/make-web-genes.py from GeneLibrary.swift. Do not edit.\n"
       f"export const SPECIES = {json.dumps(species, indent=1)};\n\n"
       f"export const COMPOUND_NAMES = {json.dumps(compounds, indent=1)};\n")
(root / "web/js/genes.js").write_text(out)
print(f"{sum(len(s['genes']) for s in species)} genes, {len(species)} species, {len(compounds)} compounds")
