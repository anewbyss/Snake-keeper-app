#!/usr/bin/env bash
# Builds SnakeKeeper.swiftpm, a Swift Playgrounds app that runs directly on iPad.
# Playgrounds apps are a single module, so the app and genetics sources are copied
# into one target and the `import SnakeGenetics` lines are dropped.
# Re-run after changing anything in App/ or SnakeGenetics/.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=SnakeKeeper.swiftpm
rm -rf "$OUT"
mkdir -p "$OUT"
cp -R App "$OUT/App"
cp -R SnakeGenetics/Sources/SnakeGenetics "$OUT/Genetics"
rm -f "$OUT/App/Info.plist"
find "$OUT" -name '*.swift' -exec sed -i.bak '/^import SnakeGenetics$/d' {} +
find "$OUT" -name '*.bak' -delete

cat > "$OUT/Package.swift" <<'SWIFT'
// swift-tools-version: 5.9

// WARNING:
// This is generated by scripts/make-playground.sh. Edits are overwritten.

import PackageDescription
import AppleProductTypes

let package = Package(
    name: "SnakeKeeper",
    platforms: [
        .iOS("17.0")
    ],
    products: [
        .iOSApplication(
            name: "SnakeKeeper",
            targets: ["AppModule"],
            bundleIdentifier: "com.example.snakekeeper",
            displayVersion: "1.0",
            bundleVersion: "1",
            appIcon: .placeholder(icon: .leaf),
            accentColor: .presetColor(.green),
            supportedDeviceFamilies: [
                .pad,
                .phone
            ],
            supportedInterfaceOrientations: [
                .portrait,
                .landscapeRight,
                .landscapeLeft,
                .portraitUpsideDown(.when(deviceFamilies: [.pad]))
            ],
            capabilities: [
                .camera(purposeString: "Take photos of your snakes.")
            ]
        )
    ],
    targets: [
        .executableTarget(
            name: "AppModule",
            path: "."
        )
    ]
)
SWIFT
echo "Wrote $OUT"
